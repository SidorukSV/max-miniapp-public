"""Command registration against isolated OneScript HTTP fixtures; no MAX calls."""
import unittest

from test_appointment_notifications import SOURCE, function_source
import test_mailing_schemas

MODULE = SOURCE / "CommonModules/бит_омни_ИнтеграцияСMAX/Ext/Module.bsl"


class BotCommands(unittest.TestCase):
    run_bsl = test_mailing_schemas.MailingSchemas.run_bsl

    def source(self):
        return "\n".join(function_source(MODULE, name) for name in (
            "МенюКомандПациентаMAX", "ЗначениеСвойства"))

    def test_preserve_custom_commands_and_idempotent_patient(self):
        self.run_bsl(self.source(), '''
Исходные = Новый Массив;
Исходные.Добавить(Новый Структура("name, description", "start", "Начать общение"));
Исходные.Добавить(Новый Структура("name", "help"));
Данные = Новый Структура("commands", Исходные);
Меню = МенюКомандПациентаMAX(Данные);
Если Не Меню.Изменено Или Меню.Команды.Количество() <> 3
    Или Меню.Команды[0].description <> "Начать общение"
    Или Меню.Команды[1].name <> "help"
    Или Меню.Команды[2].description <> "Выбрать пациента"
    Или Исходные.Количество() <> 2 Тогда
    ВызватьИсключение "Adding patient must preserve all custom commands and original input";
КонецЕсли;
Повтор = МенюКомандПациентаMAX(Новый Структура("commands", Меню.Команды));
Если Повтор.Изменено Или Повтор.Команды.Количество() <> 3 Тогда
    ВызватьИсключение "Registration must be idempotent";
КонецЕсли;
Меню.Команды[2].description = "old";
Повтор = МенюКомандПациентаMAX(Новый Структура("commands", Меню.Команды));
Если Не Повтор.Изменено Или Повтор.Команды[2].description <> "Выбрать пациента" Тогда
    ВызватьИсключение "Existing patient description must be refreshed without duplication";
КонецЕсли;
''')

    def test_empty_invalid_and_full_menus(self):
        self.run_bsl(self.source(), '''
Меню = МенюКомандПациентаMAX(Новый Структура);
Если Меню.Команды.Количество() <> 1 Или Меню.Команды[0].name <> "patient" Тогда
    ВызватьИсключение "Missing optional commands means an empty menu";
КонецЕсли;
Ошибки = Новый Массив;
Ошибки.Добавить("invalid response");
Ошибки.Добавить(Новый Структура("commands", "not an array"));
Команды = Новый Массив;
Команды.Добавить(Новый Структура("name", ""));
Ошибки.Добавить(Новый Структура("commands", Команды));
Команды = Новый Массив;
Для Индекс = 1 По 32 Цикл
    Команды.Добавить(Новый Структура("name", "command" + Строка(Индекс)));
КонецЦикла;
Ошибки.Добавить(Новый Структура("commands", Команды));
Для Каждого Данные Из Ошибки Цикл
    Отказ = Ложь;
    Попытка
        МенюКомандПациентаMAX(Данные);
    Исключение
        Отказ = Истина;
    КонецПопытки;
    Если Не Отказ Тогда ВызватьИсключение "Malformed/full menu must never be overwritten"; КонецЕсли;
КонецЦикла;
Если Команды.Количество() <> 32 Тогда ВызватьИсключение "Full input menu mutated"; КонецЕсли;
''')


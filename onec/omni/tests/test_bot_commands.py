''' + function_source(MODULE, "ЗарегистрироватьКомандыMAX").replace(
            "бит_омни_ИнтеграцияСMAXПовтИсп.", "").replace(
            "Новый HTTPЗапрос(", "Новый HTTPЗапросФикстура(") + "\n" + self.source() + '''

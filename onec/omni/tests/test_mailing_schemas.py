"""Regression tests for the actual BSL resolver and cached-mailing filter.

OneScript fixtures stand in for 1C storage/catalog types. Database queries and
real DCS metadata are validated by the separate 1C build, not by these fixtures.
"""
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from test_appointment_notifications import SOURCE, function_source


@unittest.skipUnless(shutil.which("oscript"), "OneScript is required")
class MailingSchemas(unittest.TestCase):
    def run_bsl(self, source, assertions, fixtures=None):
        with tempfile.TemporaryDirectory(prefix="omni-skd-") as temp:
            folder = Path(temp)
            setup = []
            for name, body in (fixtures or {}).items():
                file = folder / (name + ".os")
                file.write_text(body, encoding="utf-8-sig")
                setup.append(f'ПодключитьСценарий("{file}", "{name}");')
            file = folder / "tests.os"
            file.write_text(source + "\n" + "\n".join(setup) + "\n" + assertions + '\nСообщить("PASS");', encoding="utf-8-sig")
            result = subprocess.run([shutil.which("oscript"), "-encoding=utf-8", str(file)],
                                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=30)
            output = result.stdout.decode("utf-8", errors="replace")
            self.assertEqual(result.returncode, 0, output)
            self.assertIn("PASS", output)

